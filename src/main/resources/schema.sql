-- Runs on every start (spring.sql.init.mode=always): drop first so the script can run again.
-- transfer_history goes first because it references accounts.
DROP TABLE IF EXISTS transfer_history;
DROP TABLE IF EXISTS accounts;

CREATE TABLE accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number       VARCHAR(26)                 NOT NULL,
    balance              DECIMAL(17, 2)              NOT NULL,
    daily_limit_transfer DECIMAL(17, 2)              NOT NULL,
    daily_limit_used     DECIMAL(17, 2)              NOT NULL,
    daily_limit_reset_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version              BIGINT                      DEFAULT 0 NOT NULL,
    CONSTRAINT uk_account_number UNIQUE (account_number)
);

CREATE TABLE transfer_history (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id                  BIGINT                      NOT NULL,
    counterparty_account_number VARCHAR(26)                 NOT NULL,
    amount                      DECIMAL(17, 2)              NOT NULL,
    executed_at                 TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    direction                   VARCHAR(8)                  NOT NULL,
    CONSTRAINT fk_transfer_history_account FOREIGN KEY (account_id) REFERENCES accounts (id)
);

CREATE INDEX idx_transfer_history_account_id_executed_at ON transfer_history (account_id, executed_at);
